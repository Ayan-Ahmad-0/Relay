"""External Deduplicating Sink Service.

CRITICAL INVARIANT:
The sink must perform NO deduplication of its own. It records every single inbound
action request directly to a raw append log and in-memory registry, serving as the
independent external ground truth for measuring applied effects and proving crash resilience.
"""

from __future__ import annotations

import json
import os
from collections import Counter
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from fastapi import FastAPI, Request
from pydantic import BaseModel, Field

app = FastAPI(title="Relay External Deduplicating Sink Service", version="1.0.0")

SINK_LOG_PATH = Path(os.getenv("SINK_LOG_PATH", "sink_output.log"))
_RECORDS: list[dict[str, Any]] = []


class SinkRecord(BaseModel):
    idempotency_key: str = Field(..., description="Unique idempotency key generated by caller")
    tool_name: str = Field(..., description="Name of tool executing action (e.g., act_reply)")
    payload: dict[str, Any] = Field(default_factory=dict, description="Action payload")
    metadata: dict[str, Any] = Field(default_factory=dict, description="Caller metadata / context")


class SinkResponse(BaseModel):
    status: str
    record_index: int
    idempotency_key: str
    received_at: str


class SinkStats(BaseModel):
    total_received: int
    unique_keys: int
    duplicate_count: int
    duplicate_keys: list[str]


def append_to_log(entry: dict[str, Any]) -> None:
    """Appends record verbatim to raw log file without deduplication."""
    line = json.dumps(entry) + "\n"
    with open(SINK_LOG_PATH, "a", encoding="utf-8") as f:
        f.write(line)


@app.get("/health")
def health() -> dict[str, str]:
    return {"status": "healthy", "service": "relay-sink"}


@app.post("/sink", response_model=SinkResponse, status_code=200)
async def record_sink_effect(record: SinkRecord, request: Request) -> SinkResponse:
    """Record an inbound effect verbatim.

    NO DEDUPLICATION: Multiple requests with the same idempotency_key are
    intentionally accepted and logged.
    """
    timestamp = datetime.now(UTC).isoformat()
    entry = {
        "index": len(_RECORDS),
        "idempotency_key": record.idempotency_key,
        "tool_name": record.tool_name,
        "payload": record.payload,
        "metadata": record.metadata,
        "received_at": timestamp,
        "client_host": request.client.host if request.client else "unknown",
    }
    _RECORDS.append(entry)
    append_to_log(entry)

    return SinkResponse(
        status="recorded",
        record_index=entry["index"],
        idempotency_key=record.idempotency_key,
        received_at=timestamp,
    )


@app.get("/sink/records")
def get_sink_records(
    idempotency_key: str | None = None, tool_name: str | None = None
) -> list[dict[str, Any]]:
    """Retrieve all recorded effects with optional filtering."""
    records = _RECORDS
    if idempotency_key:
        records = [r for r in records if r["idempotency_key"] == idempotency_key]
    if tool_name:
        records = [r for r in records if r["tool_name"] == tool_name]
    return records


@app.get("/sink/stats", response_model=SinkStats)
def get_sink_stats() -> SinkStats:
    """Calculate duplicate counts across all received effects."""
    total = len(_RECORDS)
    key_counts = Counter(r["idempotency_key"] for r in _RECORDS)
    unique = len(key_counts)
    dup_keys = [k for k, count in key_counts.items() if count > 1]
    duplicates = sum(count - 1 for count in key_counts.values())

    return SinkStats(
        total_received=total,
        unique_keys=unique,
        duplicate_count=duplicates,
        duplicate_keys=dup_keys,
    )


@app.post("/sink/clear")
def clear_sink() -> dict[str, str]:
    """Reset the sink state and delete the raw log."""
    global _RECORDS
    _RECORDS = []
    if SINK_LOG_PATH.exists():
        try:
            SINK_LOG_PATH.unlink()
        except OSError:
            pass
    return {"status": "cleared"}


def run_service(host: str = "0.0.0.0", port: int = 8001) -> None:
    """Start uvicorn server for sink service."""
    import uvicorn

    uvicorn.run(app, host=host, port=port)


if __name__ == "__main__":
    run_service()
